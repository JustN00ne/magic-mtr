package org.justnoone.jme.client.render;

import org.justnoone.jme.block.BlockCrossingGate;

import java.util.Locale;

/**
 * The crossing gate's boom, one model per arm length. The Blockbench model's boom is 135 pixels long (11.5 blocks
 * reach); shorter booms are cut at the hinge end, so the red and white stripes keep their size and the tip always ends
 * with a full white stripe. Generated as OBJ text and loaded like the other {@link ObjBlockModel}s.
 */
final class CrossingGateModels {

    /**
     * Where the boom starts (its hinge end, in pixels above the block when raised), and how far the arm reaches from
     * the gate's centre for every pixel of boom beyond that: the hinge is 2 pixels behind the centre at 19 pixels up,
     * so a boom of {@code L} pixels reaches {@code 50 + L} pixels when lowered.
     */
    private static final int BOOM_START_Y = 67;
    private static final int REACH_BEFORE_BOOM = 50;
    private static final float TEXTURE_SIZE = 256;

    private static final ObjBlockModel[] BOOMS = new ObjBlockModel[BlockCrossingGate.MAX_LENGTH - BlockCrossingGate.MIN_LENGTH + 1];

    private CrossingGateModels() {
    }

    /**
     * @param length the arm's reach in blocks, from the centre of the gate's block
     */
    static ObjBlockModel getBoom(int length) {
        final int index = BlockCrossingGate.clampLength(length) - BlockCrossingGate.MIN_LENGTH;
        ObjBlockModel boom = BOOMS[index];
        if (boom == null) {
            final int clamped = index + BlockCrossingGate.MIN_LENGTH;
            boom = new ObjBlockModel("jme:models/obj/crossing_gate_boom_" + clamped + ".obj", "jme:textures/block/crossing_gate_arm.png", 0, createBoom(clamped * 16 - REACH_BEFORE_BOOM));
            BOOMS[index] = boom;
        }
        return boom;
    }

    static void invalidateBooms() {
        for (final ObjBlockModel boom : BOOMS) {
            if (boom != null) {
                boom.invalidate();
            }
        }
    }

    /**
     * The boom as a box 1 pixel thick and 4 wide, {@code length} pixels long, with the UVs of the Blockbench model.
     */
    private static String createBoom(int length) {
        final float x0 = -0.5F, x1 = 0.5F, z0 = -3, z1 = 1, y0 = BOOM_START_Y, y1 = BOOM_START_Y + length;
        final StringBuilder obj = new StringBuilder("# Crossing gate boom, generated by MAGIC.\nmtllib crossing_gate.mtl\no boom\nusemtl crossing_gate\n");
        final int[] count = {0};
        // Broad faces: u across the boom, v along it from the tip (0) to the hinge end (length).
        face(obj, count, new float[][]{{x1, y1, z0, 4, 0}, {x1, y1, z1, 0, 0}, {x1, y0, z1, 0, length}, {x1, y0, z0, 4, length}});
        face(obj, count, new float[][]{{x0, y0, z1, 4, length}, {x0, y1, z1, 4, 0}, {x0, y1, z0, 0, 0}, {x0, y0, z0, 0, length}});
        // Narrow edges.
        face(obj, count, new float[][]{{x1, y0, z1, 1, length}, {x1, y1, z1, 1, 0}, {x0, y1, z1, 0, 0}, {x0, y0, z1, 0, length}});
        face(obj, count, new float[][]{{x0, y0, z0, 1, length}, {x0, y1, z0, 1, 0}, {x1, y1, z0, 0, 0}, {x1, y0, z0, 0, length}});
        // Ends.
        face(obj, count, new float[][]{{x0, y1, z0, 22, 36}, {x0, y1, z1, 22, 40}, {x1, y1, z1, 23, 40}, {x1, y1, z0, 23, 36}});
        face(obj, count, new float[][]{{x0, y0, z0, 24, 36}, {x1, y0, z0, 25, 36}, {x1, y0, z1, 25, 40}, {x0, y0, z1, 24, 40}});
        return obj.toString();
    }

    /**
     * Adds a quad; each vertex is x, y, z in pixels and u, v in texture pixels, counter-clockwise seen from outside.
     */
    private static void face(StringBuilder obj, int[] count, float[][] vertices) {
        final StringBuilder f = new StringBuilder("f");
        for (final float[] vertex : vertices) {
            obj.append(String.format(Locale.ROOT, "v %.6f %.6f %.6f\nvt %.6f %.6f\n", vertex[0] / 16, vertex[1] / 16, vertex[2] / 16, vertex[3] / TEXTURE_SIZE, vertex[4] / TEXTURE_SIZE));
            count[0]++;
            f.append(' ').append(count[0]).append('/').append(count[0]);
        }
        obj.append(f).append('\n');
    }
}
